// =============================================================================
// 丸数字ヘルパ
//   同一日に複数の起床 (二度寝・仮眠) がある場合の「起床①②…」ラベル用。
//   0 始まりの index を受け取り ①〜⑳ を返す。範囲外は "(n)" にフォールバック。
// =============================================================================
const CIRCLED_NUMBERS = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳";

export function circledNumber(index: number): string {
  const char = CIRCLED_NUMBERS[index];
  return char ?? `(${index + 1})`;
}
