-- =============================================================================
-- デモデータ seed
-- =============================================================================
--
-- 【目的】
-- 公開デモページ (`/demo/daily/[date]`) が外部 API を叩かずに見栄えのする
-- データを表示できるよう、デモ専用テーブル 3 種に静的データを投入する。
--
-- 【日付の選び方】
-- 2026-05-15 / 2026-05-16 / 2026-05-17 の 3 日分。デモ画面の日付ナビゲーション
-- (前日 / 翌日) を試せるよう連続した 3 日にしている。
--
-- 【タイムゾーンの扱い】
-- 時刻はすべて UTC で格納する (timestamptz の DB 内部表現は UTC)。
-- 表示時はユーザータイムゾーン (Asia/Tokyo 想定) に変換する。
-- 例: 2026-05-14 22:30 UTC = 2026-05-15 07:30 JST
--
-- 【冪等性】
-- 各 INSERT は ON CONFLICT (外部 ID) DO NOTHING で冪等。再適用しても重複
-- エラーにならない。値を変えたい場合は別マイグレーションで UPDATE すること。
--
-- 【データ全体の構成 (2026-05-17 の例)】
--   睡眠 (Oura):
--     - 23:45 JST 就寝 → 07:00 JST 起床 (sleep_minutes=435)
--   予定 (Google Calendar):
--     - 07:30 朝のルーティン / 09:30 スタンドアップ / 10:00 ディープワーク /
--       12:00 ランチ / 14:00 読書 / 16:00 1on1
--   作業 (Toggl):
--     - 10:00 Today’s ME 実装 / 13:00 Today’s ME 実装 / 15:30 ドキュ整理 /
--       16:30 MVP 設計
-- =============================================================================

